"""Regenerate the Word manual from the Markdown specification.

The manual under ``docs/`` is a Pandoc render of ``docs/spec/项目规格.md``.  It
used to be regenerated by hand, which meant a documentation round could forget
it and leave the Word file a release behind.  This script makes that step a
command with its own post-checks:

* Pandoc must succeed and produce a non-empty ``.docx``.
* Every XML part must be readable UTF-8 with **zero** U+FFFD replacement
  characters (the usual symptom of a broken encoding round-trip).
* The document must contain body paragraphs and at least one table, so a
  silently truncated render fails loudly.

It also writes a build record (``docs/spec/manual-build.json``) holding the source
digest and the Pandoc version, so a later run can tell "the manual is stale" apart
from "a different Pandoc renders slightly differently" -- without the record the
two cases look identical.  Both the manual and the record are local build
artifacts and are not tracked.

It prints the measurements it checked.  Exit code 0 means all checks passed;
anything else means the output was not replaced.

Usage::

    python scripts/build_manual.py
    python scripts/build_manual.py --pandoc /d/Anaconda/Library/bin/pandoc
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "docs" / "spec" / "项目规格.md"
DEFAULT_OUTPUT = ROOT / "docs" / "spec" / "TicketPilot项目说明书.docx"
DEFAULT_RECORD = ROOT / "docs" / "spec" / "manual-build.json"

_W_P = re.compile(r"<w:p[ >]")
_W_TBL = re.compile(r"<w:tbl[ >]")


def _find_pandoc(explicit: str | None) -> str:
    if explicit:
        return explicit
    found = shutil.which("pandoc")
    if found:
        return found
    raise SystemExit("pandoc not found on PATH; pass --pandoc /path/to/pandoc")


def pandoc_version(pandoc: str) -> str:
    """The Pandoc version string, e.g. ``3.8``."""

    completed = subprocess.run(
        [pandoc, "--version"], capture_output=True, text=True, check=False
    )
    first = (completed.stdout or completed.stderr).splitlines()
    if not first:
        return "unknown"
    parts = first[0].split()
    return parts[1] if len(parts) > 1 else first[0].strip()


def source_digest(source: Path) -> str:
    """sha256 of the source with CRLF normalized to LF.

    ``.gitattributes`` pins ``eol=lf``: a clean clone holds LF bytes while a
    local working tree may hold CRLF, so the digest must be line-ending
    agnostic or the guard only passes on one machine.
    """

    raw = source.read_bytes().replace(b"\r\n", b"\n")
    return hashlib.sha256(raw).hexdigest()


def _inspect(path: Path) -> dict[str, int]:
    """Return measurements for a .docx, raising on a malformed archive."""
    stats = {"bytes": path.stat().st_size, "paragraphs": 0, "tables": 0, "fffd": 0, "parts": 0}
    with zipfile.ZipFile(path) as archive:
        for name in archive.namelist():
            if not name.endswith(".xml"):
                continue
            raw = archive.read(name)
            text = raw.decode("utf-8")
            stats["parts"] += 1
            stats["fffd"] += text.count("\ufffd")
            if name == "word/document.xml":
                stats["paragraphs"] = len(_W_P.findall(text))
                stats["tables"] = len(_W_TBL.findall(text))
    return stats


def build(source: Path, output: Path, pandoc: str) -> dict[str, int]:
    if not source.is_file():
        raise SystemExit(f"source not found: {source}")
    output.parent.mkdir(parents=True, exist_ok=True)

    # Render next to the target, then replace, so a failed run leaves the
    # previous manual intact instead of truncating it.
    handle, temp_name = tempfile.mkstemp(suffix=".docx", dir=output.parent)
    os.close(handle)
    temp = Path(temp_name)
    try:
        command = [pandoc, str(source), "-f", "gfm", "-t", "docx", "-o", str(temp)]
        completed = subprocess.run(command, capture_output=True, text=True, check=False)
        if completed.returncode != 0:
            raise SystemExit(
                f"pandoc failed with exit {completed.returncode}\n"
                f"stdout: {completed.stdout}\nstderr: {completed.stderr}"
            )

        stats = _inspect(temp)
        problems: list[str] = []
        if stats["bytes"] < 50_000:
            problems.append(f"output too small: {stats['bytes']} bytes")
        if stats["paragraphs"] < 1_000:
            problems.append(f"too few body paragraphs: {stats['paragraphs']}")
        if stats["tables"] < 1:
            problems.append("no tables rendered")
        if stats["fffd"] != 0:
            problems.append(f"U+FFFD replacement characters: {stats['fffd']}")
        if problems:
            raise SystemExit("manual check failed: " + "; ".join(problems))

        temp.replace(output)
        return stats
    finally:
        temp.unlink(missing_ok=True)


def write_record(record: Path, source: Path, pandoc: str, stats: dict[str, int]) -> None:
    """Write the build record the documentation guard reads.

    The record is deterministic: same source plus same Pandoc gives the same
    file, so rebuilding an unchanged manual does not dirty the tree.
    """

    payload = {
        "source": source.relative_to(ROOT).as_posix(),
        "source_sha256": source_digest(source),
        "pandoc": pandoc_version(pandoc),
        "bytes": stats["bytes"],
        "paragraphs": stats["paragraphs"],
        "tables": stats["tables"],
    }
    record.parent.mkdir(parents=True, exist_ok=True)
    record.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--record", type=Path, default=DEFAULT_RECORD)
    parser.add_argument("--pandoc", help="pandoc executable (default: search PATH)")
    args = parser.parse_args(argv)

    pandoc = _find_pandoc(args.pandoc)
    source = args.source if args.source.is_absolute() else (ROOT / args.source)
    output = args.output if args.output.is_absolute() else (ROOT / args.output)
    record = args.record if args.record.is_absolute() else (ROOT / args.record)
    stats = build(source, output, pandoc)
    write_record(record, source, pandoc, stats)
    print(f"pandoc: {pandoc} ({pandoc_version(pandoc)})")
    print(f"source: {source.relative_to(ROOT).as_posix()}")
    print(f"output: {output.relative_to(ROOT).as_posix()}")
    print(f"record: {record.relative_to(ROOT).as_posix()}")
    print(
        f"bytes={stats['bytes']} paragraphs={stats['paragraphs']} "
        f"tables={stats['tables']} fffd={stats['fffd']} parts={stats['parts']}"
    )
    print("MANUAL OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
