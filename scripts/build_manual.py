"""Regenerate the Word manual from the Markdown specification.

The manual under ``docs/`` is a Pandoc render of ``docs/PROJECT_SPEC.md``.  It
used to be regenerated by hand, which meant a documentation round could forget
it and leave the Word file a release behind.  This script makes that step a
command with its own post-checks:

* Pandoc must succeed and produce a non-empty ``.docx``.
* Every XML part must be readable UTF-8 with **zero** U+FFFD replacement
  characters (the usual symptom of a broken encoding round-trip).
* The document must contain body paragraphs and at least one table, so a
  silently truncated render fails loudly.

It prints the measurements it checked.  Exit code 0 means all checks passed;
anything else means the output was not replaced.

Usage::

    python scripts/build_manual.py
    python scripts/build_manual.py --pandoc /d/Anaconda/Library/bin/pandoc
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "docs" / "PROJECT_SPEC.md"
DEFAULT_OUTPUT = ROOT / "docs" / "TicketPilot项目说明书.docx"

_W_P = re.compile(r"<w:p[ >]")
_W_TBL = re.compile(r"<w:tbl[ >]")


def _find_pandoc(explicit: str | None) -> str:
    if explicit:
        return explicit
    found = shutil.which("pandoc")
    if found:
        return found
    raise SystemExit("pandoc not found on PATH; pass --pandoc /path/to/pandoc")


def _inspect(path: Path) -> dict[str, int]:
    """Return measurements for a .docx, raising on a malformed archive."""
    stats = {"bytes": path.stat().st_size, "paragraphs": 0, "tables": 0, "fffd": 0, "parts": 0}
    with zipfile.ZipFile(path) as archive:
        for name in archive.namelist():
            if not name.endswith(".xml"):
                continue
            raw = archive.read(name)
            text = raw.decode("utf-8")
            stats["parts"] += 1
            stats["fffd"] += text.count("\ufffd")
            if name == "word/document.xml":
                stats["paragraphs"] = len(_W_P.findall(text))
                stats["tables"] = len(_W_TBL.findall(text))
    return stats


def build(source: Path, output: Path, pandoc: str) -> dict[str, int]:
    if not source.is_file():
        raise SystemExit(f"source not found: {source}")
    output.parent.mkdir(parents=True, exist_ok=True)

    # Render next to the target, then replace, so a failed run leaves the
    # previous manual intact instead of truncating it.
    handle, temp_name = tempfile.mkstemp(suffix=".docx", dir=output.parent)
    os.close(handle)
    temp = Path(temp_name)
    try:
        command = [pandoc, str(source), "-f", "gfm", "-t", "docx", "-o", str(temp)]
        completed = subprocess.run(command, capture_output=True, text=True, check=False)
        if completed.returncode != 0:
            raise SystemExit(
                f"pandoc failed with exit {completed.returncode}\n"
                f"stdout: {completed.stdout}\nstderr: {completed.stderr}"
            )

        stats = _inspect(temp)
        problems: list[str] = []
        if stats["bytes"] < 50_000:
            problems.append(f"output too small: {stats['bytes']} bytes")
        if stats["paragraphs"] < 1_000:
            problems.append(f"too few body paragraphs: {stats['paragraphs']}")
        if stats["tables"] < 1:
            problems.append("no tables rendered")
        if stats["fffd"] != 0:
            problems.append(f"U+FFFD replacement characters: {stats['fffd']}")
        if problems:
            raise SystemExit("manual check failed: " + "; ".join(problems))

        temp.replace(output)
        return stats
    finally:
        temp.unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--pandoc", help="pandoc executable (default: search PATH)")
    args = parser.parse_args(argv)

    pandoc = _find_pandoc(args.pandoc)
    source = args.source if args.source.is_absolute() else (ROOT / args.source)
    output = args.output if args.output.is_absolute() else (ROOT / args.output)
    stats = build(source, output, pandoc)
    print(f"pandoc: {pandoc}")
    print(f"source: {source.relative_to(ROOT).as_posix()}")
    print(f"output: {output.relative_to(ROOT).as_posix()}")
    print(
        f"bytes={stats['bytes']} paragraphs={stats['paragraphs']} "
        f"tables={stats['tables']} fffd={stats['fffd']} parts={stats['parts']}"
    )
    print("MANUAL OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
